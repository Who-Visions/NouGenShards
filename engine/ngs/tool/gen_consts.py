# Derive every crypto constant from its definition with exact integer math.
def primes(n):
    out=[];k=2
    while len(out)<n:
        if all(k%p for p in out if p*p<=k): out.append(k)
        k+=1
    return out
def iroot(x,r):
    lo,hi=0,1
    while hi**r<=x: hi*=2
    while lo<hi-1:
        m=(lo+hi)//2
        if m**r<=x: lo=m
        else: hi=m
    return lo
def frac_bits(p,r,bits):  # first `bits` bits of frac(p**(1/r))
    v=iroot(p<<(bits*r),r)
    return v & ((1<<bits)-1)
P=primes(80)
sha512_k=[frac_bits(p,3,64) for p in P]
sha512_iv=[frac_bits(p,2,64) for p in P[:8]]
blake3_iv=[frac_bits(p,2,32) for p in P[:8]]
q=2**255-19
d=(-121665*pow(121666,q-2,q))%q
I=pow(2,(q-1)//4,q)
By=(4*pow(5,q-2,q))%q
# recover x from y: x^2 = (y^2-1)/(d y^2+1), even x
xx=((By*By-1)*pow(d*By*By+1,q-2,q))%q
Bx=pow(xx,(q+3)//8,q)
if (Bx*Bx-xx)%q: Bx=(Bx*I)%q
if Bx&1: Bx=q-Bx
def gf(v): return "{"+",".join("0x%04x"%((v>>(16*i))&0xffff) for i in range(16))+"}"
L=2**252+27742317777372353535851937790883648493
out=[]
out.append("/* generated by tool/gen_consts.py from the algorithm definitions; do not edit */")
out.append("static const uint64_t SHA512_K[80] = {"+",".join("UINT64_C(0x%016x)"%k for k in sha512_k)+"};")
out.append("static const uint64_t SHA512_IV[8] = {"+",".join("UINT64_C(0x%016x)"%k for k in sha512_iv)+"};")
out.append("static const uint32_t BLAKE3_IV[8] = {"+",".join("0x%08xu"%k for k in blake3_iv)+"};")
for n,v in (("ED_D",d),("ED_D2",2*d%q),("ED_I",I),("ED_BX",Bx),("ED_BY",By)):
    out.append("static const ngs__gf %s = %s;"%(n,gf(v)))
out.append("static const int64_t ED_L[32] = {"+",".join("0x%02x"%((L>>(8*i))&0xff) for i in range(32))+"};")
print("\n".join(out))
