"""Regenerate test/abi_asserts.h: a compile-time offsetof/sizeof assertion for every public struct member."""
import os, re
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
h = re.sub(r'/\*.*?\*/', '', open(os.path.join(root, 'include', 'ngs.h')).read(), flags=re.S)
out, n = [], 0
for m in re.finditer(r'typedef struct\s*\{([^{}]*)\}\s*(\w+);', h):
    body, name = m.groups()
    out.append('_Static_assert(sizeof(%s) > 0, "%s");\n' % (name, name)); n += 1
    for d in body.split(';'):
        d = d.strip()
        fm = re.findall(r'(\w+)(?:\[[^\]]*\])?$', d.replace('*', ' ')) if d else []
        if fm:
            out.append('_Static_assert(offsetof(%s, %s) < sizeof(%s), "%s.%s");\n' % (name, fm[0], name, name, fm[0])); n += 1
out.append('#define NGS_ABI_ASSERT_COUNT %d\n' % n)
with open(os.path.join(root, 'test', 'abi_asserts.h'), 'w', newline='\n') as fh:
    fh.write('/* SPDX-License-Identifier: Apache-2.0 */\n/* Generated by tool/gen_abi.py from include/ngs.h. */\n#include <stddef.h>\n#include "ngs.h"\n' + ''.join(out))
print(n, 'assertions')
