"""Build dist/nougenshards.c (one file, builds alone next to dist/ngs.h).

Order: the internal header first (its feature macros must precede every
system header), then each source with its local includes inlined once.
"""
import pathlib, re, shutil, sys
root = pathlib.Path(__file__).resolve().parent.parent
src = root / "src"
order = ["ngs_internal.h", "plat_posix.c", "crypto.c", "cbor.c", "log.c"]
seen = set()
def inline(path):
    out = []
    for line in path.read_text().splitlines():
        m = re.match(r'\s*#include "([^"]+)"', line)
        if m:
            name = m.group(1)
            if name == "ngs.h":
                out.append('#include "ngs.h"'); continue
            if name in seen: continue
            seen.add(name)
            out.append("/* ---- begin %s ---- */" % name)
            out.extend(inline(src / name))
            out.append("/* ---- end %s ---- */" % name)
            continue
        out.append(line)
    return out
lines = ["/* nougenshards.c -- NGS M1 amalgamation (generated by tool/amalgamate.py; do not edit). Apache-2.0. */"]
for f in order:
    if f in seen: continue
    seen.add(f)
    lines.append("/* ==== %s ==== */" % f)
    lines.extend(inline(src / f))
dist = root / "dist"; dist.mkdir(exist_ok=True)
(dist / "nougenshards.c").write_text("\n".join(lines) + "\n")
shutil.copy(root / "include" / "ngs.h", dist / "ngs.h")
print("dist/nougenshards.c:", len(lines), "lines")
