"""Amalgamate the NGS M1 core and its vendored crypto into dist/nougenshards.c + dist/ngs.h.

The amalgamation is one translation unit. Local #include "..." lines that resolve to a file already
emitted are dropped; system includes stay. Static names that collide between the vendored Ed25519 files
are renamed with a per-file prefix through #define / #undef pairs around each file.
"""
import os
import re
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIST = os.path.join(ROOT, "dist")

ORDER = [
    "third_party/blake3/blake3.h", "third_party/blake3/blake3_impl.h",
    "third_party/blake3/blake3_portable.c", "third_party/blake3/blake3_dispatch.c", "third_party/blake3/blake3.c",
    "third_party/ed25519/fixedint.h", "third_party/ed25519/fe.h", "third_party/ed25519/ge.h", "third_party/ed25519/sc.h",
    "third_party/ed25519/sha512.h", "third_party/ed25519/ed25519.h", "third_party/ed25519/precomp_data.h",
    "third_party/ed25519/fe.c", "third_party/ed25519/ge.c", "third_party/ed25519/keypair.c",
    "third_party/ed25519/sc.c", "third_party/ed25519/sha512.c", "third_party/ed25519/sign.c",
    "third_party/ed25519/verify.c",
    "src/plat.h", "src/ngs_int.h",
    "src/hash.c", "src/sign.c", "src/cbor.c", "src/plat_win32.c", "src/plat_posix.c", "src/log.c", "src/api.c",
]

LIBC_NAMES = {"select"}          # static names that collide with <sys/select.h> once POSIX headers are in the same TU
INC = re.compile(r'^\s*#\s*include\s+"([^"]+)"\s*$')
STATIC_FN = re.compile(r'^static\s+(?:inline\s+)?(?:const\s+)?[A-Za-z_][\w\s\*]*?\b([A-Za-z_]\w*)\s*\(', re.M)


def read(rel):
    with open(os.path.join(ROOT, rel), encoding="utf-8", newline="") as fh:
        return fh.read().replace("\r\n", "\n")


def main():
    emitted = {os.path.normpath(os.path.join(ROOT, "include", "ngs.h"))}
    for rel in ORDER:
        emitted.add(os.path.normpath(os.path.join(ROOT, rel)))
    out = []
    out.append("/* SPDX-License-Identifier: Apache-2.0 */\n"
               "/* nougenshards.c -- NouGenShards (NGS) M1 amalgamation. Generated by tool/amalgamate.py; do not edit.\n"
               "** Contains: NGS core (Apache-2.0), BLAKE3 portable (CC0-1.0 OR Apache-2.0), orlp/ed25519 (zlib).\n"
               "** Pins and hashes of the vendored sources: engine/ngs/third_party/VERSIONS. */\n"
               "#ifndef _WIN32\n#ifndef _POSIX_C_SOURCE\n#define _POSIX_C_SOURCE 200809L\n#endif\n#ifndef _DEFAULT_SOURCE\n#define _DEFAULT_SOURCE 1\n#endif\n#if defined(__APPLE__) && !defined(_DARWIN_C_SOURCE)\n#define _DARWIN_C_SOURCE 1\n#endif\n#endif\n#define BLAKE3_NO_SSE2\n#define BLAKE3_NO_SSE41\n#define BLAKE3_NO_AVX2\n#define BLAKE3_NO_AVX512\n"
               "#define BLAKE3_USE_NEON 0\n#if defined(__clang__) || defined(__GNUC__)\n#pragma GCC diagnostic ignored \"-Wunused-function\"\n#pragma GCC diagnostic ignored \"-Wunused-variable\"\n#endif\n#include \"ngs.h\"\n")
    seen = set()
    for rel in ORDER:
        text = read(rel)
        base = os.path.dirname(os.path.join(ROOT, rel))
        body = []
        for line in text.split("\n"):
            m = INC.match(line)
            if m:
                target = os.path.normpath(os.path.join(base, m.group(1)))
                if target in emitted:
                    if m.group(1).endswith("ngs.h") or target.endswith(os.path.join("include", "ngs.h")):
                        continue
                    continue                                  # already emitted earlier in the order
            body.append(line)
        text = "\n".join(body)
        prefix = ""
        suffix = ""
        if rel.startswith("third_party/ed25519/") and rel.endswith(".c"):
            tag = "ed25519_" + os.path.basename(rel)[:-2] + "__"
            names = sorted(set(STATIC_FN.findall(text)) - {"main"})
            clash = [n for n in names if n in seen or n in LIBC_NAMES]
            seen.update(names)
            for n in clash:
                prefix += "#define %s %s%s\n" % (n, tag, n)
                suffix += "#undef %s\n" % n
        out.append("\n/* ==== %s ==== */\n" % rel)
        if rel.startswith("third_party/"):
            out.append("#if defined(__clang__) || defined(__GNUC__)\n#pragma GCC diagnostic push\n"
                       "#pragma GCC diagnostic ignored \"-Wpedantic\"\n#endif\n")
        out.append(prefix + text + "\n" + suffix)
        if rel.startswith("third_party/"):
            out.append("#if defined(__clang__) || defined(__GNUC__)\n#pragma GCC diagnostic pop\n#endif\n")
    os.makedirs(DIST, exist_ok=True)
    with open(os.path.join(DIST, "nougenshards.c"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("".join(out))
    shutil.copyfile(os.path.join(ROOT, "include", "ngs.h"), os.path.join(DIST, "ngs.h"))
    size = os.path.getsize(os.path.join(DIST, "nougenshards.c"))
    print("amalgamation: dist/nougenshards.c (%d bytes, %d lines) + dist/ngs.h" % (size, "".join(out).count("\n")))


if __name__ == "__main__":
    sys.exit(main())
